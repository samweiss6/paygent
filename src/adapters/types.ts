// The adapter contract. Adapters are untrusted: they see only what is in AdapterContext.
// Full guide: docs/adapter-authoring.md

/**
 * How an issuer's cards are funded:
 *  - "usdc_deposit": the issuer accepts USDC at an address (wallet and on-ramp paths).
 *  - "fiat_linked":  the issuer charges the owner's bank account or debit card that the owner
 *                    linked in the provider's own app (direct fiat path; no crypto).
 */
export type FundingModel = "usdc_deposit" | "fiat_linked";

interface ManifestBase {
  id: string;                    // lowercase, [a-z0-9-], unique
  displayName: string;
  version: string;
  /** Hosts the adapter may call. The owner approves these when installing. */
  allowedHosts: string[];
  /** v0.1 only runs in test mode; adapters must refuse live credentials. */
  testModeOnly: true;
}

export interface IssuerManifest extends ManifestBase {
  kind: "issuer";
  fundingModels: FundingModel[];
  capabilities: {
    singleUse: boolean;
    merchantLock: "none" | "first_use" | "domain";
    perCardCap: boolean;
    expiry: boolean;
    freeze: boolean;
  };
}

export interface OnrampManifest extends ManifestBase {
  kind: "onramp";
  /** Assets/networks the on-ramp can deliver, e.g. ["USDC:base-sepolia"]. */
  delivers: string[];
}

export type AdapterManifest = IssuerManifest | OnrampManifest;

export interface CreateCardRequest {
  amountCents: number;       // hard cap to set on the card
  merchant: string;          // normalized merchant domain (for memo / lock hint)
  expiresAt: string;         // ISO; card must not be usable after this
  idempotencyKey: string;
  memo: string;              // short, generated by core, no agent text
}

/** What an issuer returns. Core moves pan/cvv into the vault and never stores them elsewhere. */
export interface IssuedCard {
  providerCardId: string;
  pan: string;
  cvv: string;
  expMonth: string;          // "MM"
  expYear: string;           // "YYYY"
  last4: string;
  /** What the provider says it actually configured; verified by core against the request. */
  controls: { singleUse: boolean; capCents: number | null; expiresAt: string | null };
}

export type CardState = "open" | "frozen" | "closed" | "used";

export interface CardStatus {
  state: CardState;
  /** Settled or authorized transactions on this card, as reported by the provider. */
  transactions: { amountCents: number; merchantDescriptor: string; status: "pending" | "settled" | "declined" }[];
}

export interface IssuerAdapter {
  readonly manifest: IssuerManifest;
  createCard(req: CreateCardRequest): Promise<IssuedCard>;
  freezeCard(providerCardId: string): Promise<void>;
  getCardStatus(providerCardId: string): Promise<CardStatus>;
  /** Test mode helper: simulate a merchant charge, if the provider sandbox supports it. */
  simulateCharge?(providerCardId: string, amountCents: number, descriptor: string): Promise<void>;
}

export interface AdapterLogger {
  info(msg: string, data?: Record<string, unknown>): void;
  warn(msg: string, data?: Record<string, unknown>): void;
}

export interface AdapterContext {
  config: Record<string, string | number | boolean>;
  apiKey: string | null;
  /** fetch restricted to manifest.allowedHosts over https. */
  http: (url: string, init?: RequestInit) => Promise<Response>;
  log: AdapterLogger;
  testMode: true;
}

export type IssuerAdapterFactory = (ctx: AdapterContext) => IssuerAdapter;

/**
 * On-ramp adapter: turns the owner's fiat into USDC delivered to the owner's own wallet.
 * Top-ups are an owner action (KYC and payment happen in the provider's hosted page, in the
 * owner's browser). The agent never triggers a top-up, and the adapter never sees bank or
 * card details: it only creates a session and reports its status.
 */
export interface TopUpRequest {
  amountCents: number;
  /** Owner's wallet address, taken from signed config. */
  destinationAddress: string;
  asset: string;               // e.g. "USDC:base-sepolia"
  idempotencyKey: string;
}

export interface TopUpSession {
  providerSessionId: string;
  /** URL the owner opens in their browser to complete KYC and payment with the provider. */
  hostedUrl: string;
  expiresAt: string;
}

export type TopUpState = "created" | "pending" | "completed" | "failed" | "expired";

export interface OnrampAdapter {
  readonly manifest: OnrampManifest;
  createTopUp(req: TopUpRequest): Promise<TopUpSession>;
  getTopUpStatus(providerSessionId: string): Promise<{ state: TopUpState; deliveredUnits: string | null; txHash: string | null }>;
  /** Test mode helper: mark a session completed (provider sandboxes usually have an equivalent). */
  simulateComplete?(providerSessionId: string): Promise<void>;
}

export type OnrampAdapterFactory = (ctx: AdapterContext) => OnrampAdapter;
